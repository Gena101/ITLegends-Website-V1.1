// scripts/font-fallbacks.mjs
// Generates metric-matched fallback @font-face rules (prevents layout shift when the web fonts swap in).
// Run once, or after changing fonts:  node scripts/font-fallbacks.mjs   → writes src/font-fallbacks.css (commit it)
import { writeFile } from 'node:fs/promises';
import { createFontStack } from '@capsizecss/core';
import inter from '@capsizecss/metrics/inter';
import spaceGrotesk from '@capsizecss/metrics/spaceGrotesk';
import arial from '@capsizecss/metrics/arial';
import roboto from '@capsizecss/metrics/roboto';

/** Fallback faces, in this order: [name suffix, metrics] */
const FALLBACKS = [
  ['Arial', arial], // Windows, macOS, iOS (+ Liberation Sans on Linux: same metrics)
  ['Roboto', roboto], // Android
];

const FONTS = [
  ['Inter', inter],
  ['Space Grotesk', spaceGrotesk],
];

const blocks = [];
const families = {};

for (const [label, metrics] of FONTS) {
  const { fontFaces } = createFontStack([metrics, ...FALLBACKS.map(([, m]) => m)]);

  // Give the generated faces predictable names: "Inter Fallback Arial", "Inter Fallback Roboto", …
  let i = 0;
  let css = fontFaces.replace(/font-family:\s*(["'])[^"']+\1/g, () => {
    const name = `${label} Fallback ${FALLBACKS[i++]?.[0]}`;
    return `font-family: "${name}"`;
  });
  // Linux has Liberation Sans (Arial-compatible metrics) instead of Arial
  css = css.replace(/local\((["'])Arial\1\)(,\s*local\((["'])ArialMT\3\))?/g, "local('Arial'), local('ArialMT'), local('Liberation Sans')");

  const expected = FALLBACKS.map(([suffix]) => `${label} Fallback ${suffix}`);
  if (i !== FALLBACKS.length || !expected.every((name) => css.includes(name)) || !css.includes('size-adjust')) {
    console.error(`Unexpected output from createFontStack for ${label}:\n${fontFaces}`);
    process.exit(1);
  }

  families[label] = expected;
  blocks.push(`/* ${label} */\n${css.trim()}`);
}

const header =
  '/* Generated by scripts/font-fallbacks.mjs (Capsize metrics). Do not edit by hand. */\n' +
  '/* Metric-matched local fallbacks: text keeps its line breaks when the web fonts swap in (CLS). */\n\n';

await writeFile(new URL('../src/font-fallbacks.css', import.meta.url), header + blocks.join('\n\n') + '\n');

console.log('Wrote src/font-fallbacks.css');
for (const [label, names] of Object.entries(families)) console.log(`  ${label}: ${names.map((n) => `"${n}"`).join(', ')}`);